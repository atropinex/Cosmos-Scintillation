import type {CosmosColumn, CosmosDatabase, CosmosTable, EngineDefinition} from "../CommonInterface";
import {autoMode} from "../utils/ColumnHelper";
import {toKebab} from "../utils/IdHelper";
import type {GeneratedOutput} from "./ExportTypes";

// === Writes a database design as a script the real database understands === //
// Nothing here talks to a database. The files are text that the user runs themselves.

/** What an engine's types mean to the writers: "int", "float", "bool", "date", "json" or "string". */
function kindOf(type: string): string {
    const text = type.toLowerCase();
    if (/^(bool|boolean|bit)\b/.test(text)) {
        return "bool";
    }
    if (/^(tinyint|smallint|mediumint|bigint|int|integer|long|serial)\b/.test(text)) {
        return "int";
    }
    if (/^(real|float|double|decimal|numeric|money)\b/.test(text)) {
        return "float";
    }
    if (/^(json|jsonb|object|array)\b/.test(text)) {
        return "json";
    }
    return /^(date|time|timestamp|datetime)/.test(text) ? "date" : "string";
}

/** A name that is safe to write between quotes: the quote character is doubled, line breaks are removed. */
function quoteName(name: string, quote: string): string {
    const clean = name.replace(/[\r\n\0]/g, " ");
    if (quote === "[") {
        return `[${clean.replace(/]/g, "]]")}]`;
    }
    return `${quote}${clean.split(quote).join(quote + quote)}${quote}`;
}

/** A default value as text from the user. It is always written as a quoted value, so it is never run as SQL. */
function sqlDefault(column: CosmosColumn, engine: EngineDefinition): string {
    const value = column.default.replace(/[\r\n\0]/g, " ");
    const kind = kindOf(column.type);
    if (kind === "bool") {
        return /^(true|1|yes)$/i.test(value) ? engine.sql.trueLiteral : engine.sql.falseLiteral;
    }
    if ((kind === "int" || kind === "float") && /^-?\d+(\.\d+)?$/.test(value)) {
        return value;
    }
    return `'${value.replace(/'/g, "''")}'`;
}

// === SQL === //

function writeSql(database: CosmosDatabase, engine: EngineDefinition, notes: string[]): string {
    const {quote, autoIncrement, tableSuffix} = engine.sql;
    const q = (name: string) => quoteName(name, quote);
    const tableById = new Map(database.tables.map((table) => [table.id, table]));
    const lines: string[] = [`-- ${database.name} (${engine.name}). Written by Cosmos-Scintillation.`];

    if (engine.sql.header.trim()) {
        lines.push(engine.sql.header.replace(/\{db\}/g, q(database.name)).trim());
    }
    lines.push("");

    // A table that points at another one must come after it, so the order follows the references.
    const ordered: CosmosTable[] = [];
    const visiting = new Set<string>();
    const visit = (table: CosmosTable) => {
        if (ordered.includes(table) || visiting.has(table.id)) {
            return;
        }
        visiting.add(table.id);
        for (const column of table.columns) {
            const target = column.ref ? tableById.get(column.ref.tableId) : undefined;
            if (target && target !== table) {
                visit(target);
            }
        }
        visiting.delete(table.id);
        ordered.push(table);
    };
    database.tables.forEach(visit);

    for (const table of ordered) {
        if (table.columns.length === 0) {
            notes.push(`"${table.name}" has no columns, so it was skipped.`);
            continue;
        }

        const parts: string[] = [];
        const primary = table.columns.filter((column) => column.primary);
        for (const column of table.columns) {
            let text = `    ${q(column.name)} ${column.type}`;
            if (column.autoIncrement && autoMode(column.type) === "id") {
                const generator: Record<string, string> = {
                    postgresql: "gen_random_uuid()", mysql: "(UUID())", mariadb: "(UUID())", sqlserver: "NEWID()"
                };
                if (generator[engine.id]) {
                    text += ` DEFAULT ${generator[engine.id]}`;
                } else {
                    notes.push(`${engine.name} cannot create ids by itself, so "${table.name}.${column.name}" must be given a value when a row is added.`);
                }
            } else if (column.autoIncrement) {
                if (autoIncrement === "serial") {
                    text = `    ${q(column.name)} ${/big/i.test(column.type) ? "BIGSERIAL" : "SERIAL"}`;
                } else if (autoIncrement === "auto_increment") {
                    text += " AUTO_INCREMENT";
                } else if (autoIncrement === "identity") {
                    text += engine.id === "sqlserver" ? " IDENTITY(1,1)" : " GENERATED BY DEFAULT AS IDENTITY";
                } else if (autoIncrement === "autoincrement") {
                    text += primary.length === 1 ? " PRIMARY KEY AUTOINCREMENT" : "";
                } else {
                    notes.push(`${engine.name} has no auto-increment, "${table.name}.${column.name}" was written without it.`);
                }
            }
            if (!column.nullable && !column.primary) {
                text += " NOT NULL";
            }
            if (column.default !== "" && !column.autoIncrement) {
                text += ` DEFAULT ${sqlDefault(column, engine)}`;
            }
            if (column.unique && !column.primary) {
                text += " UNIQUE";
            }
            parts.push(text);
        }

        const inlineKey = autoIncrement === "autoincrement" && primary.some((column) => column.autoIncrement && autoMode(column.type) === "count") && primary.length === 1;
        if (primary.length > 0 && !inlineKey) {
            parts.push(`    PRIMARY KEY (${primary.map((column) => q(column.name)).join(", ")})`);
        }

        for (const column of table.columns) {
            const target = column.ref ? tableById.get(column.ref.tableId) : undefined;
            const targetColumn = target?.columns.find((item) => item.id === column.ref?.columnId);
            if (column.ref && target && targetColumn) {
                parts.push(`    FOREIGN KEY (${q(column.name)}) REFERENCES ${q(target.name)} (${q(targetColumn.name)}) ON DELETE ${column.ref.onDelete.toUpperCase()}`);
            }
        }

        lines.push(`CREATE TABLE ${q(table.name)} (\n${parts.join(",\n")}\n)${tableSuffix ? " " + tableSuffix : ""};`, "");
    }
    return lines.join("\n");
}

// === MongoDB === //

const BSON: Record<string, string> = {
    objectid: "objectId", string: "string", int: "int", long: "long", double: "double", decimal: "decimal",
    bool: "bool", date: "date", object: "object", array: "array", bindata: "binData"
};

function writeMongo(database: CosmosDatabase, notes: string[]): string {
    const lines = [
        `// ${database.name} (MongoDB). Written by Cosmos-Scintillation.`,
        `// Run with: mongosh --file ${toKebab(database.name)}.js`,
        `const database = db.getSiblingDB(${JSON.stringify(database.name)});`,
        ""
    ];
    const tableById = new Map(database.tables.map((table) => [table.id, table]));

    for (const table of database.tables) {
        const required = table.columns.filter((column) => !column.nullable && column.name !== "_id").map((column) => column.name);
        const properties: Record<string, unknown> = {};
        for (const column of table.columns) {
            const bsonType = BSON[column.type.toLowerCase()] ?? "string";
            properties[column.name] = {bsonType: column.nullable ? [bsonType, "null"] : bsonType};
            const target = column.ref ? tableById.get(column.ref.tableId) : undefined;
            if (column.ref && target) {
                notes.push(`"${table.name}.${column.name}" refers to "${target.name}". MongoDB does not enforce references, so the app must keep them correct.`);
            }
        }
        const validator = {$jsonSchema: {bsonType: "object", required, properties}};
        lines.push(`database.createCollection(${JSON.stringify(table.name)}, {validator: ${JSON.stringify(validator, null, 2)}});`);

        for (const column of table.columns.filter((item) => item.unique && item.name !== "_id")) {
            lines.push(`database.getCollection(${JSON.stringify(table.name)}).createIndex({${JSON.stringify(column.name)}: 1}, {unique: true});`);
        }
        lines.push("");
    }
    return lines.join("\n");
}

// === Redis === //

function writeRedis(database: CosmosDatabase): string {
    const lines = [
        `# ${database.name} (Redis). Written by Cosmos-Scintillation.`,
        "# Redis has no tables. Each key group below is a key pattern, and its fields are the parts of the value.",
        ""
    ];
    for (const table of database.tables) {
        const key = table.columns.find((column) => column.primary) ?? table.columns[0];
        lines.push(`## ${table.name}`, `Key pattern: ${table.name}:{${key?.name ?? "id"}}`, "Fields:");
        for (const column of table.columns) {
            lines.push(`  - ${column.name}: ${column.type}${column.nullable ? " (optional)" : ""}${column.default ? ` = ${JSON.stringify(column.default)}` : ""}`);
        }
        lines.push("");
    }
    return lines.join("\n");
}

// === Entry point === //

/** Turns a database design into one script file, picked by the engine's `exporter`. */
export function exportDatabase(database: CosmosDatabase, engine: EngineDefinition | undefined): GeneratedOutput {
    const notes: string[] = [];
    if (!engine) {
        return {files: [], notes: [`The engine "${database.engine}" is not installed, so this database cannot be exported.`]};
    }
    if (database.tables.length === 0) {
        notes.push("This database has no tables yet.");
    }

    let content: string;
    if (engine.exporter === "mongo") {
        content = writeMongo(database, notes);
    } else if (engine.exporter === "redis") {
        content = writeRedis(database);
    } else {
        content = writeSql(database, engine, notes);
    }

    const name = `${toKebab(database.name, "database")}.${engine.scriptExtension || "txt"}`;
    return {files: [{path: name, content}], notes: [...new Set(notes)]};
}
